package com.plantorganizer.plantinfo;

/** Where a care profile came from, shown to the user so they can judge how much to trust it. */
public enum InfoSource {

    PERENUAL("Perenual plant database", false),
    AI_GENERATED("AI-generated by Cohere from web search results (lower reliability, please double-check)", true);

    private final String label;
    private final boolean lowerReliability;

    InfoSource(String label, boolean lowerReliability) {
        this.label = label;
        this.lowerReliability = lowerReliability;
    }

    public String getLabel() {
        return label;
    }

    public boolean isLowerReliability() {
        return lowerReliability;
    }
}
